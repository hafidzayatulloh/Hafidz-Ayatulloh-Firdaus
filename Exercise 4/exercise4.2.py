animals = ["kucing", "anjing", "kelinci"]

# Langkah 1: cetak nama setiap hewan
for animal in animals:
    print(animal)

print()  # baris kosong sebagai pemisah

# Langkah 2: cetak kalimat untuk setiap hewan
for animal in animals:
    print(f"Seekor {animal} akan menjadi hewan peliharaan yang hebat.")

# Langkah 3: kalimat penutup di luar loop
print("\nHewan apa pun dari daftar ini akan menjadi hewan peliharaan yang hebat!")